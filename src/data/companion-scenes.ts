/** CO-2-A2-2 서명 (D-536 서사 리뷰 A4): 첫째 왕관 결말에서 녹은 동료의 이름 — THR-2에서 도금왕 갑옷 속 태엽의 이름으로 다시 나온다 */
const signed = (t: string, prev?: string[]): string => {
  const who = signerOf(prev);
  return who ? t.replace(/」$/, ` — ${who}」`) : t;
};
/** 왕관별 그림 (받기 전엔 alt — docs/asset-order-master.md D-451) */
const CO2_ART = ['companion-crossroad', 'old-spring', 'companion-crossroad', 'scarred-wall'];
/** prev = 앞 왕관 결말에서 녹은 동료 이름(출하 기록) — 둘째 왕관 벽 글씨의 서명 */
export const companionScene = (act: number, alive: CompanionActor[], promise?: StoryPromise, chapter = 0, prev?: string[]): { cuts: Cut[]; promise?: StoryPromise } => {
  const actor = (promise ? alive.find((u) => u.serial === promise.serial) : undefined) ?? alive.find((u) => u.t === 'P') ?? alive[0];
  const ch = Math.max(0, Math.min(3, chapter));
  let made = promise;
  const lines: Line[] = [];
  let img = 'credits-bg';
  let alt: string | undefined;
  if (act === 0) {
    // CO-1-없음-1 (D-612 — 리뷰 A-1 #1): 동료가 없으면 「분대가 둘러앉았다」 대신 혼자 앉는다
    lines.push({ k: 'n', t: actor ? '첫 번째 공정을 간신히 넘긴 밤, 기름 냄새가 진동하는 상자 구석에 지친 분대가 둘러앉았다.' : '첫 번째 공정을 간신히 넘긴 밤, 기름 냄새가 진동하는 상자 구석에 그는 혼자 앉았다.' });
    if (actor) {
      made = { serial: actor.serial ?? '', name: actor.name, wish: WISH[actor.t] };
      lines.push({ k: 's', who: actor.name, t: made.wish }, { k: 's', who: '종이왕', t: PROMISE[ch] });
      img = 'companion-rest';
    } else lines.push({ k: 'n', t: '그 곁에 둘러앉을 동료는 하나도 남아 있지 않았다.' });
  } else if (act === 1) {
    lines.push({ k: 'n', t: '두 번째 공정이 끝났다. 짙은 쇳내와 화약 연기가 가시고, 승강기 틈새로 서늘한 바람이 스며들었다.' });
    if (TRACE[ch]) lines.push({ k: 'n', t: ch === 1 ? signed(TRACE[ch], prev) : TRACE[ch] });
    if (actor) lines.push({ k: 's', who: actor.name, t: OWN_WAY[actor.t] }, { k: 's', who: '종이왕', t: '그래. 바깥세상에 나가면, 그땐 나도 너희에게 명령하지 않을게. 각자 가고 싶은 곳으로 가자.' });
    lines.push({ k: 'm', t: actor ? DOUBT[ch] : DOUBT_ALONE[ch] });
    if (actor || TRACE[ch]) { img = CO2_ART[ch]; alt = 'companion-crossroad'; }
  } else {
    lines.push({ k: 'n', t: '출하구로 가는 마지막 계단 앞에는, 끝내 승급하지 못한 채 부서진 옛 불량 세트들의 낡은 상자들이 산처럼 쌓여 있었다.' }, { k: 'n', t: '그리고 그 너머로, 출하구로 통하는 거대한 문이 안쪽에서 쇠사슬로 칭칭 감겨 잠겨 있었다. 먼 데서 들리던 쇠사슬 소리의 주인이었다.' });
    const [reply, mono, alone] = DOOR[ch];
    if (actor) lines.push({ k: 's', who: actor.name, t: ASK_DOOR[actor.t] }, { k: 's', who: '종이왕', t: reply });
    lines.push({ k: 'm', t: actor ? mono : alone });
    img = 'chained-door';
    alt = 'departure-dock';
  }
  // 전용 원화는 인물이 그림 안에 있으므로 기물을 겹치지 않는다. 동료가 없으면 동료가 그려진 그림 대신 옛 배경
  const scene = img !== 'credits-bg';
  return { promise: made, cuts: [{ img, alt, bg: ['#16141c', '#0b0b0e'], art: [], lines, ...(scene ? { pixelCover: true, cam: 'still' as const } : { standIn: true }) }] };
};
