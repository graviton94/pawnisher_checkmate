/** 한 줄: n = 서술 · s = 대사(who 이름) · m = 속말 */
export interface Line { k: 'n' | 's' | 'm'; t: string; who?: string }
export interface Cut {
  img: string;
  bg: [string, string];
  glow?: string;
  art: StandIn[];
  fx?: 'alarm' | 'red' | 'spot' | 'path' | 'gold';
  /**
   * 카메라 (테스터 피드백: 모든 배경이 한 방향으로 흘렀다) — 장면 속 요소에 맞춰 천천히 움직인다.
   * pan-l/pan-r = 카메라가 왼/오른쪽으로 · tilt-u/tilt-d = 위/아래로 · in/out = 다가감/물러남 (at = 초점, 화면 % "x% y%") · still = 가만히
   */
  cam?: 'pan-l' | 'pan-r' | 'tilt-u' | 'tilt-d' | 'in' | 'out' | 'still';
  at?: string;
  lines: Line[];
  /** 두 번째 출하부터 「프롤로그 다시 보기」에 나오는 컷 */
  key?: boolean;
}

const n = (t: string): Line => ({ k: 'n', t });
const s = (who: string, t: string): Line => ({ k: 's', who, t });
const m = (t: string): Line => ({ k: 'm', t });
const P = (x: number, y: number, h: number, o: Partial<StandIn> = {}): StandIn => ({ t: 'P', side: 0, x, y, h, ...o });

