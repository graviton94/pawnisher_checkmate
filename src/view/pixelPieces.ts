/** 진영별 팔레트: 흰 기물(플레이어) · 검은 기물(적). 둘 다 바깥은 흰 테두리 (참고 이미지) */
const PALETTE: Record<Side, { outer: string; line: string; fill: string; shade: string; light: string }> = {
  0: { outer: '#f4f1ea', line: '#16141c', fill: '#efece6', shade: '#b8b3c2', light: '#ffffff' },
  1: { outer: '#f4f1ea', line: '#0a090d', fill: '#2c2a35', shade: '#17161d', light: '#4a4757' },
};

export const PIXEL_SIZE = 18; // 16 + 바깥 테두리 1픽셀씩

/** 기물 하나를 18×18 캔버스에 그린다 */
export const drawPixelPiece = (type: PieceType, side: Side): HTMLCanvasElement => {
  const shape = SHAPES[type];
  const pal = PALETTE[side];
  const c = document.createElement('canvas');
  c.width = c.height = PIXEL_SIZE;
  const g = c.getContext('2d')!;
  const solid = (x: number, y: number) => y >= 0 && y < 16 && x >= 0 && x < 16 && shape[y][x] !== '.';
  const px = (x: number, y: number, color: string) => {
    g.fillStyle = color;
    g.fillRect(x + 1, y + 1, 1, 1);
  };
  // 바깥 흰 테두리: 몸에 붙은 빈칸
  for (let y = -1; y <= 16; y++)
    for (let x = -1; x <= 16; x++) {
      if (solid(x, y)) continue;
      if (solid(x + 1, y) || solid(x - 1, y) || solid(x, y + 1) || solid(x, y - 1)) px(x, y, pal.outer);
    }
  for (let y = 0; y < 16; y++) {
    const row = shape[y];
    const xs = [...row].map((ch, x) => (ch !== '.' ? x : -1)).filter((x) => x >= 0);
    const right = Math.max(...xs, -1);
    const left = Math.min(...xs, 99);
    for (let x = 0; x < 16; x++) {
      const ch = row[x];
      if (ch === '.') continue;
      const edge = !solid(x + 1, y) || !solid(x - 1, y) || !solid(x, y + 1) || !solid(x, y - 1);
      let color = pal.fill;
      if (edge || ch === 'k') color = pal.line;
      else if (x >= right - 2) color = pal.shade; // 오른쪽 그늘
      else if (x <= left + 1 && y < 9) color = pal.light; // 머리 왼쪽 빛
      px(x, y, color);
    }
  }
  return c;
};

/** Phaser 텍스처 키 */
export const pieceKey = (type: PieceType, side: Side) => `px-${type}-${side}`;
